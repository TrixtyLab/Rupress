use std::path::Path;

/**
 * Resolves standard MIME types based on file extensions.
 */
pub fn get_mime_type(path: &Path) -> &'static str {
    match path.extension().and_then(|s| s.to_str()).unwrap_or("").to_ascii_lowercase().as_str() {
        "html" | "htm" => "text/html; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "js" | "mjs" => "application/javascript; charset=utf-8",
        "json" | "jsonld" => "application/json; charset=utf-8",
        "map" => "application/json; charset=utf-8",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "svg" => "image/svg+xml",
        "webp" => "image/webp",
        "avif" => "image/avif",
        "ico" | "cur" => "image/x-icon",
        "wasm" => "application/wasm",
        "pdf" => "application/pdf",
        "txt" | "text" => "text/plain; charset=utf-8",
        "xml" => "application/xml; charset=utf-8",
        "csv" => "text/csv; charset=utf-8",
        "mp4" => "video/mp4",
        "webm" => "video/webm",
        "mp3" => "audio/mpeg",
        "ogg" => "audio/ogg",
        "wav" => "audio/wav",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "eot" => "application/vnd.ms-fontobject",
        "zip" => "application/zip",
        "gz" => "application/gzip",
        "tar" => "application/x-tar",
        _ => "application/octet-stream",
    }
}

/**
 * Builds the `Cache-Control` header of a static file.
 *
 * The entry point of a SPA is never cached, and the assets with a content hash in
 * their name (the ones generated by Vite, Rollup or webpack) are cached forever.
 */
pub fn cache_control(file_name: &str, max_age: u32, immutable_max_age: u32) -> String {
    if file_name.eq_ignore_ascii_case("index.html") {
        return "no-cache".to_string();
    }

    if is_hashed_asset(file_name) {
        return format!("public, max-age={}, immutable", immutable_max_age);
    }

    format!("public, max-age={}", max_age)
}

/**
 * Detects the assets with a content hash in their name (`index-a1B2c3D4.js`).
 */
fn is_hashed_asset(file_name: &str) -> bool {
    let stem = Path::new(file_name)
        .file_stem()
        .map(|value| value.to_string_lossy().to_string())
        .unwrap_or_default();

    // Vite and Rollup: `name-<hash>.ext`
    if let Some((_, hash)) = stem.rsplit_once('-') {
        if looks_like_hash(hash) {
            return true;
        }
    }

    // webpack: `name.<hash>.ext`
    if let Some((_, hash)) = stem.rsplit_once('.') {
        if looks_like_hash(hash) {
            return true;
        }
    }

    false
}

/**
 * Checks whether a fragment of a file name looks like a content hash.
 *
 * A hash mixes letters and digits (or uses upper case), so a regular word such as
 * `environment` is not mistaken for one.
 */
fn looks_like_hash(value: &str) -> bool {
    if value.len() < 8 {
        return false;
    }

    if !value
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        return false;
    }

    let has_digit = value.chars().any(|c| c.is_ascii_digit());
    let has_upper = value.chars().any(|c| c.is_ascii_uppercase());

    has_digit || has_upper
}
